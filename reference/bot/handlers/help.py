async def help_handler(event):
    match = event.pattern_match
    page_number_bytes = match.group(2) # Group 2 is the (\d+) part
    
    if page_number_bytes:
        current_page = int(page_number_bytes.decode('utf-8'))
    else:
        current_page = 1
    page_index = current_page - 1
    total_pages = len(HELP_PAGES)

    try:
        help_text = HELP_PAGES[page_index]
    except IndexError:
        current_page = 1
        page_index = 0
        help_text = HELP_PAGES[page_index]
    nav_buttons = []
    if current_page > 1:
        nav_buttons.append(Button.inline("⬅️ السابق", data=f"help:page:{current_page - 1}"))

    if current_page < total_pages:
        nav_buttons.append(Button.inline("التالي ➡️", data=f"help:page:{current_page + 1}"))

    buttons = []
    if nav_buttons:
        buttons.append(nav_buttons)
    
    buttons.append([Button.inline("↩️ القائمة الرئيسية", b"main_menu")])

    final_text = f"**دليل الاستخدام (صفحة {current_page}/{total_pages})**\n"
    final_text += "✨" + "━" * 15 + "✨\n\n"
    final_text += help_text

    await safe_edit_message(event, final_text, buttons=buttons)


def setup(client_instance: "TelegramClient"):
    """Registers all help handlers with the TelegramClient."""
    client_instance.on(events.CallbackQuery(pattern=rb"help(:page:(\d+))?"))(help_handler)
    print("✅ Help handlers registered.")